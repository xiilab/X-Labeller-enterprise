package com.xlabeller.models;

public class DatasetLogVO {
	
	private String dataset_log_id;
	private String dataset_id;
	private String log_info;
	private String created_date;
	
	private String page_num;
	private String page_size;
	private String total_size;
	
	
	
	public String getDataset_log_id() {
		return dataset_log_id;
	}
	public void setDataset_log_id(String dataset_log_id) {
		this.dataset_log_id = dataset_log_id;
	}
	public String getDataset_id() {
		return dataset_id;
	}
	public void setDataset_id(String dataset_id) {
		this.dataset_id = dataset_id;
	}
	public String getLog_info() {
		return log_info;
	}
	public void setLog_info(String log_info) {
		this.log_info = log_info;
	}
	public String getCreated_date() {
		return created_date;
	}
	public void setCreated_date(String created_date) {
		this.created_date = created_date;
	}
	public String getPage_num() {
		return page_num;
	}
	public void setPage_num(String page_num) {
		this.page_num = page_num;
	}
	public String getPage_size() {
		return page_size;
	}
	public void setPage_size(String page_size) {
		this.page_size = page_size;
	}
	public String getTotal_size() {
		return total_size;
	}
	public void setTotal_size(String total_size) {
		this.total_size = total_size;
	}
	
	
	
	
	
}
